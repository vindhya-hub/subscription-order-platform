-- Portable between PostgreSQL and H2 (used for local development and tests).

CREATE TABLE customers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120)             NOT NULL,
    email      VARCHAR(254)             NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_customers_email UNIQUE (email)
);

CREATE TABLE plans (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(40)              NOT NULL,
    name        VARCHAR(120)             NOT NULL,
    description VARCHAR(500),
    unit_price  NUMERIC(10, 2)           NOT NULL,
    currency    VARCHAR(3)               NOT NULL,
    active      BOOLEAN                  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_plans_code UNIQUE (code),
    CONSTRAINT ck_plans_unit_price CHECK (unit_price >= 0)
);

CREATE TABLE subscriptions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   BIGINT                   NOT NULL,
    plan_id       BIGINT                   NOT NULL,
    quantity      INTEGER                  NOT NULL,
    frequency     VARCHAR(16)              NOT NULL,
    status        VARCHAR(16)              NOT NULL,
    anchor_date   DATE                     NOT NULL,
    cycle_index   INTEGER                  NOT NULL,
    next_run_date DATE                     NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    cancelled_at  TIMESTAMP WITH TIME ZONE,
    version       BIGINT                   NOT NULL,
    CONSTRAINT fk_subscriptions_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT fk_subscriptions_plan FOREIGN KEY (plan_id) REFERENCES plans (id),
    CONSTRAINT ck_subscriptions_quantity CHECK (quantity BETWEEN 1 AND 100),
    CONSTRAINT ck_subscriptions_frequency CHECK (frequency IN ('WEEKLY', 'BIWEEKLY', 'MONTHLY')),
    CONSTRAINT ck_subscriptions_status CHECK (status IN ('ACTIVE', 'PAUSED', 'CANCELLED'))
);

-- The billing run looks up ACTIVE subscriptions by next run date.
CREATE INDEX ix_subscriptions_status_next_run ON subscriptions (status, next_run_date);
CREATE INDEX ix_subscriptions_customer ON subscriptions (customer_id);

CREATE TABLE orders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT                   NOT NULL,
    run_date        DATE                     NOT NULL,
    quantity        INTEGER                  NOT NULL,
    unit_price      NUMERIC(10, 2)           NOT NULL,
    amount          NUMERIC(12, 2)           NOT NULL,
    currency        VARCHAR(3)               NOT NULL,
    status          VARCHAR(16)              NOT NULL,
    attempts        INTEGER                  NOT NULL,
    last_error      VARCHAR(500),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    fulfilled_at    TIMESTAMP WITH TIME ZONE,
    version         BIGINT                   NOT NULL,
    CONSTRAINT fk_orders_subscription FOREIGN KEY (subscription_id) REFERENCES subscriptions (id),
    -- One order per subscription per billing cycle: the backstop that keeps billing idempotent.
    CONSTRAINT uk_orders_subscription_run_date UNIQUE (subscription_id, run_date),
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'PROCESSING', 'FULFILLED', 'FAILED'))
);

CREATE INDEX ix_orders_status ON orders (status);

-- Transactional outbox: events written with the state change, published to SNS afterwards.
CREATE TABLE outbox_events (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type   VARCHAR(40)              NOT NULL,
    aggregate_id     BIGINT                   NOT NULL,
    event_type       VARCHAR(60)              NOT NULL,
    payload          VARCHAR(4000)            NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at     TIMESTAMP WITH TIME ZONE,
    message_id       VARCHAR(100),
    publish_attempts INTEGER                  NOT NULL,
    last_error       VARCHAR(500)
);

CREATE INDEX ix_outbox_events_unpublished ON outbox_events (published_at, id);
